int SizeX = sizeof(World) / sizeof(World[0]);
int SizeY = sizeof(World[0]) / sizeof(World[0][0]);
bool IsExit = false;

struct
{
	int x;
	int y;
}Player;


void Input() 
{
	if (GetAsyncKeyState(VK_ESCAPE)) 
	{
		IsExit = true;
		return;
	}

	int newX = Player.x, newY = Player.y;

	if (GetAsyncKeyState('W')) 
		newX--;
	else if (GetAsyncKeyState('S')) 
		newX++;
	else if (GetAsyncKeyState('A')) 
		newY--;
	else if (GetAsyncKeyState('D')) 
		newY++;
	else 
		return; 

	if (newX >= 0 && newX < SizeX && newY >= 0 && newY < SizeY) 
	{
		if (World[newX][newY] != "-") 
		{
			Player.x = newX;
			Player.y = newY;
		}
	}
}

void UpdateWorld() 
{
	for (int x = 0; x < SizeX; ++x)
	{
		for (int y = 0; y < SizeY; ++y)
		{
			if (World[x][y] != "-")
				World[x][y] = ".";
		}
	}

	World[Player.x][Player.y] = "@";
}

void Render() 
{
	HANDLE hConsole = GetStdHandle(STD_OUTPUT_HANDLE);
	if (hConsole == INVALID_HANDLE_VALUE)
		return;

	std::string buffer;
	buffer.reserve(SizeX * SizeY);
	for (int x = 0; x < SizeX; ++x) 
	{
		for (int y = 0; y < SizeY; ++y) 
		{
			buffer += World[x][y];
		}
	}

	DWORD written;
	WriteConsoleOutputCharacterA(hConsole, buffer.c_str(),(DWORD)buffer.size(),{ 0, 0 }, &written);
}

int main() {
	setlocale(0, "");
	system(("mode con cols=" + std::to_string(SizeY) + " lines=" + std::to_string(SizeX)).c_str());
	Player.x = 1;
	Player.y = 1;

	while (!IsExit) 
	{
		Input();
		UpdateWorld();
		Sleep(16);
		Render();
	}
	return 0;
}