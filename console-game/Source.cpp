int SizeX = sizeof(World) / sizeof(World[0]);
int SizeY = sizeof(World[0]) / sizeof(World[0][0]);
bool IsExit = false;
int SizeEnemy = -1;

struct
{
	int hp = 100;
	int x;
	int y;
} Player;

void Input() 
{
	if (GetAsyncKeyState(VK_ESCAPE)) 
	{
		IsExit = true;
		return;
	}

	int newX = Player.x, newY = Player.y;

	if (GetAsyncKeyState('W')) 
		newX--;
	else if (GetAsyncKeyState('S')) 
		newX++;
	else if (GetAsyncKeyState('A')) 
		newY--;
	else if (GetAsyncKeyState('D')) 
		newY++;
	else 
		return; 

	if (newX >= 0 && newX < SizeX && newY >= 0 && newY < SizeY) 
	{
		if (World[newX][newY] != "-" && World[newX][newY] != "|")
		{
			Player.x = newX;
			Player.y = newY;
		}
		if (World[newX][newY] == "#")
		{
			Player.hp -= 20;
			Player.x = newX;
			Player.y = newY;
		}
		if (World[newX][newY] == "%")
		{
			Player.hp += 20;
			Player.x = newX;
			Player.y = newY;
		}
	}
}

void UpdateWorld() 
{
	SizeEnemy = 0;
	for (int x = 0; x < SizeX; ++x)
	{
		for (int y = 0; y < SizeY; ++y)
		{
			if (World[x][y] == "#")
				SizeEnemy++;

			if (World[x][y] != "-" && World[x][y] != "|" && World[x][y] != "#" && World[x][y] != "%" && x < 24)
				World[x][y] = ".";
		}
	}

	World[Player.x][Player.y] = "@";
}

WORD GetColorForChar(char ch) 
{
	switch (ch) 
	{
	case '#': return FOREGROUND_RED | FOREGROUND_INTENSITY;  
	case '%': return FOREGROUND_GREEN | FOREGROUND_INTENSITY;  
	case '@': return FOREGROUND_RED | FOREGROUND_GREEN | FOREGROUND_INTENSITY; 
	case '-': return FOREGROUND_BLUE | FOREGROUND_GREEN | FOREGROUND_RED; 
	case '|': return FOREGROUND_BLUE | FOREGROUND_GREEN | FOREGROUND_RED;
	default:  return FOREGROUND_RED | FOREGROUND_GREEN | FOREGROUND_BLUE;
	}
}

void RenderText(std::vector<CHAR_INFO>& buffer,int& x, int& y)
{
	if (World[x][y] == "*HP")
	{
		string tempText = to_string(Player.hp);

		for (int i = 0; i < tempText.size(); i++)
		{
			int idx = x * SizeY + y;
			buffer[idx].Char.AsciiChar = tempText[i];
			buffer[idx].Attributes = WORD(FOREGROUND_RED | FOREGROUND_GREEN | FOREGROUND_BLUE);
			y++;
		}
	}
	if (World[x][y] == "*ENEMY")
	{
		string tempText = to_string(SizeEnemy);

		for (int i = 0; i < tempText.size(); i++)
		{
			int idx = x * SizeY + y;
			buffer[idx].Char.AsciiChar = tempText[i];
			buffer[idx].Attributes = WORD(FOREGROUND_RED | FOREGROUND_GREEN | FOREGROUND_BLUE);
			y++;
		}
	}

}

void Render() 
{
	HANDLE hConsole = GetStdHandle(STD_OUTPUT_HANDLE);
	if (hConsole == INVALID_HANDLE_VALUE) return;

	std::vector<CHAR_INFO> buffer(SizeX * SizeY);
	for (int x = 0; x < SizeX; ++x) 
	{
		for (int y = 0; y < SizeY; ++y) 
		{
			int idx = x * SizeY + y;
			if (World[x][y][0] != '*')
			{
				buffer[idx].Char.AsciiChar = World[x][y][0];
				buffer[idx].Attributes = GetColorForChar(World[x][y][0]);
			}
			else
				RenderText(buffer, x, y);
		}
	}
	COORD bufSize = { (SHORT)SizeY, (SHORT)SizeX };
	COORD bufCoord = { 0, 0 };
	SMALL_RECT writeRegion = { 0, 0, (SHORT)(SizeY - 1), (SHORT)(SizeX - 1) };
	WriteConsoleOutputA(hConsole, buffer.data(), bufSize, bufCoord, &writeRegion);

}

int main() {
	setlocale(0, "");
	system(("mode con cols=" + std::to_string(SizeY) + " lines=" + std::to_string(SizeX)).c_str());
	Player.x = 1;
	Player.y = 1;

	while (!IsExit) 
	{
		if (Player.hp <= 0 || SizeEnemy == 0)
		{
			break;
		}
		else 
		{
			Input();
			UpdateWorld();
			Sleep(32);
			Render();
		}
	}

	if (Player.hp <= 0)
	{
		system("cls");
		cout << "Ты проиграл!";
	}
	else if (Player.hp > 0 && 1)
	{
		system("cls");
		cout << "Ты выйграл!";
	}

	return 0;
}